// Fetch all detailed monthly sheets (01-2569 .. 09-2569) from Google Sheet workbook (.xlsx export)
// and regenerate src/data/allMonthsData.js + src/data/all18BranchesData.js cleanly.
import fs from 'node:fs';
import path from 'node:path';
import {
  MASTER_SPREADSHEET_ID,
  MASTER_XLSX_URL,
  extractMonthlySheetsFromBuffer
} from './src/utils/sheetWorkbookSync.js';

async function main() {
  console.log(`Fetching master workbook XLSX from ${MASTER_XLSX_URL}...`);
  const res = await fetch(MASTER_XLSX_URL);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status}: ${res.statusText}`);
  }
  const buf = await res.arrayBuffer();
  const sheetsMap = extractMonthlySheetsFromBuffer(buf);
  const sortedKeys = Object.keys(sheetsMap).sort();

  if (sortedKeys.length === 0) {
    throw new Error('No MM-25XX sheets extracted from workbook');
  }

  const monthsData = {};
  console.log('\nSummary per detailed monthly sheet:');
  for (const key of sortedKeys) {
    const m = sheetsMap[key];
    monthsData[key] = {
      key: m.key,
      label: m.label,
      sheetName: m.sheetName,
      source: m.source,
      csv: m.csv,
      note: `ข้อมูลรายข้อครบทั้ง ${m.branches.length} สาขา จากแผ่นงาน "${m.sheetName}" (${m.vehicleCount} คัน, รางวัลรวม ฿${m.totalReward.toLocaleString()})`
    };
    console.log(
      `  ${key} [${m.sheetName}] (${m.label}): ${m.vehicleCount} vehicles, ${m.branches.length} branches, totalReward=฿${m.totalReward.toLocaleString()} (${m.csv.length} bytes)`
    );
  }

  const allMonthsPath = path.resolve('src/data/allMonthsData.js');
  const outCode =
    `// Auto-generated by sync_looker_months.mjs from Google Sheet tabs 01-2569..09-2569 (Spreadsheet ${MASTER_SPREADSHEET_ID})\n` +
    `export const MASTER_SPREADSHEET_ID = '${MASTER_SPREADSHEET_ID}';\n` +
    `export const MASTER_XLSX_URL = '${MASTER_XLSX_URL}';\n` +
    `export const LOOKER_SPREADSHEET_ID = '${MASTER_SPREADSHEET_ID}';\n` +
    `export const LOOKER_GID = '2115397650';\n` +
    `export const LOOKER_CSV_URL = 'https://docs.google.com/spreadsheets/d/${MASTER_SPREADSHEET_ID}/export?format=csv&gid=2115397650';\n\n` +
    `export const PRELOADED_MONTHS = ${JSON.stringify(monthsData, null, 2)};\n`;

  fs.writeFileSync(allMonthsPath, outCode, 'utf8');
  console.log(`\nWrote ${allMonthsPath} (${Buffer.byteLength(outCode, 'utf8').toLocaleString()} bytes)`);

  const latestKey = sortedKeys[sortedKeys.length - 1];
  if (latestKey) {
    const latestPath = path.resolve('src/data/all18BranchesData.js');
    const latestCode =
      `// Clean re-export referencing latest detailed month (${latestKey})\n` +
      `import { PRELOADED_MONTHS } from './allMonthsData.js';\n\n` +
      `export const ALL_18_BRANCHES_MONTH_2569_09 = PRELOADED_MONTHS['${latestKey}']?.csv || '';\n`;
    fs.writeFileSync(latestPath, latestCode, 'utf8');
    console.log(`Updated ${latestPath} (referencing ${latestKey}, 0 duplicate CSV bytes)`);
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
