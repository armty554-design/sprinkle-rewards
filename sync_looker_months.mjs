import fs from 'fs';
import path from 'path';
import Papa from 'papaparse';

export const LOOKER_SPREADSHEET_ID = '1GdiQEkdAUT8JLMQEnaFOlV6o5goWm2j_v1HXney7hZc';
export const LOOKER_GID = '2115397650';
export const LOOKER_CSV_URL = `https://docs.google.com/spreadsheets/d/${LOOKER_SPREADSHEET_ID}/export?format=csv&gid=${LOOKER_GID}`;

const THAI_MONTH_NAMES = {
  '01': 'มกราคม',
  '02': 'กุมภาพันธ์',
  '03': 'มีนาคม',
  '04': 'เมษายน',
  '05': 'พฤษภาคม',
  '06': 'มิถุนายน',
  '07': 'กรกฎาคม',
  '08': 'สิงหาคม',
  '09': 'กันยายน',
  '10': 'ตุลาคม',
  '11': 'พฤศจิกายน',
  '12': 'ธันวาคม'
};

function normalizeMonthKey(raw) {
  const m = String(raw || '').trim().match(/^(\d{4})-(\d{1,2})$/);
  if (!m) return null;
  let y = parseInt(m[1], 10);
  if (y < 2400) y += 543;
  const mm = m[2].padStart(2, '0');
  return `${y}-${mm}`;
}

function formatThaiMonthLabel(key) {
  const [y, mm] = String(key).split('-');
  return `${THAI_MONTH_NAMES[mm] || mm} ${y}`;
}

function parseNum(v) {
  const n = parseFloat(String(v || '').replace(/,/g, '').trim());
  return Number.isNaN(n) ? 0 : n;
}

async function main() {
  console.log(`Fetching Looker 69 CSV from ${LOOKER_CSV_URL}...`);
  const res = await fetch(LOOKER_CSV_URL);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} fetching Looker sheet`);
  }
  const csvText = await res.text();
  const parsed = Papa.parse(csvText, { skipEmptyLines: false });
  const rows = parsed.data || [];
  if (rows.length < 2) {
    throw new Error(`Unexpected row count: ${rows.length}`);
  }

  const headerRow = rows[0];
  const monthIdx = headerRow.findIndex(c => String(c || '').trim() === 'เดือน');
  const branchIdx = headerRow.findIndex(c => String(c || '').trim() === 'สาขา');
  const carIdx = headerRow.findIndex(c => String(c || '').trim() === 'เบอร์รถ');
  const rewardIdx = headerRow.findIndex(c => String(c || '').trim() === 'รวมเงินรางวัล');

  if (monthIdx < 0 || branchIdx < 0 || carIdx < 0 || rewardIdx < 0) {
    throw new Error(`Missing required Looker columns (month=${monthIdx}, branch=${branchIdx}, car=${carIdx}, reward=${rewardIdx})`);
  }

  const byMonth = new Map();
  for (let i = 1; i < rows.length; i++) {
    const r = rows[i];
    if (!r || r.length < 10) continue;
    const carCode = String(r[carIdx] || '').trim();
    const monthKey = normalizeMonthKey(r[monthIdx]);
    if (!carCode || !monthKey) continue;

    if (!byMonth.has(monthKey)) {
      byMonth.set(monthKey, []);
    }
    byMonth.get(monthKey).push(r);
  }

  const sortedKeys = Array.from(byMonth.keys()).sort();
  const monthsData = {};

  console.log('\nSummary per month:');
  for (const key of sortedKeys) {
    const mRows = byMonth.get(key);
    const branches = new Set(mRows.map(r => String(r[branchIdx] || '').trim()).filter(Boolean));
    const totalReward = mRows.reduce((sum, r) => sum + parseNum(r[rewardIdx]), 0);
    const csv = Papa.unparse([headerRow, ...mRows], { newline: '\r\n' });
    const label = formatThaiMonthLabel(key);

    monthsData[key] = {
      key,
      label,
      gid: LOOKER_GID,
      source: 'looker69',
      isLooker: true,
      csv
    };

    console.log(`  ${key} (${label}): ${mRows.length} vehicles, ${branches.size} branches, totalReward=฿${totalReward.toLocaleString()} (${csv.length} bytes)`);
  }

  const allMonthsPath = path.resolve('src/data/allMonthsData.js');
  const outCode = `// Auto-generated by sync_looker_months.mjs from Google Sheet "Looker ผลคะแนนแยกกลุ่มงาน69" (gid=${LOOKER_GID})\n` +
    `export const LOOKER_SPREADSHEET_ID = '${LOOKER_SPREADSHEET_ID}';\n` +
    `export const LOOKER_GID = '${LOOKER_GID}';\n` +
    `export const LOOKER_CSV_URL = 'https://docs.google.com/spreadsheets/d/${LOOKER_SPREADSHEET_ID}/export?format=csv&gid=${LOOKER_GID}';\n\n` +
    `export const PRELOADED_MONTHS = ${JSON.stringify(monthsData, null, 2)};\n`;

  fs.writeFileSync(allMonthsPath, outCode, 'utf8');
  console.log(`\nWrote ${allMonthsPath} (${Buffer.byteLength(outCode, 'utf8').toLocaleString()} bytes)`);

  const latestKey = sortedKeys[sortedKeys.length - 1];
  if (latestKey) {
    const latestPath = path.resolve('src/data/all18BranchesData.js');
    const latestCode = `// Clean re-export referencing latest Looker 69 month (${latestKey}) — legacy 170-col snapshot removed\n` +
      `import { PRELOADED_MONTHS } from './allMonthsData.js';\n\n` +
      `export const ALL_18_BRANCHES_MONTH_2569_09 = PRELOADED_MONTHS['${latestKey}']?.csv || '';\n`;
    fs.writeFileSync(latestPath, latestCode, 'utf8');
    console.log(`Updated ${latestPath} (referencing ${latestKey}, 0 duplicate CSV bytes)`);
  }
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
